#!/usr/bin/env python3
"""Build lawful-ui.md: the whole skill as one file, for chat windows and tools with no skill support.

Run from the repository root after editing anything under skills/lawful-ui/:
    python3 scripts/build-single-file.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "lawful-ui"
PARTS = [
    ("references/build.md", "Part 2"),
    ("references/test.md", "Part 3"),
    ("references/laws.md", "Part 4"),
    ("references/ui-laws.md", "Part 5"),
    ("references/components.md", "Part 6"),
    ("references/web.md", "Part 7"),
    ("references/mobile.md", "Part 8"),
    ("assets/report-template.md", "Part 9"),
]


def demote(text):
    """Push every heading down one level so each file nests under its part heading."""
    out, fenced = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        out.append("#" + line if (line.startswith("#") and not fenced) else line)
    return "\n".join(out)


body = re.sub(r"^---\n.*?\n---\n", "", (SKILL / "SKILL.md").read_text(), count=1, flags=re.S).strip()
chunks = [
    "<!-- Generated by scripts/build-single-file.py. Edit the files under skills/lawful-ui/ instead. -->",
    "",
    "> This is lawful-ui as a single file. Paste it into a chat, or reference it from your agent's instruction file.",
    "> Wherever the text names a file (`references/laws.md`, `assets/report-template.md`, and so on), that file is",
    "> included below as a part of this document. The measuring scripts are not included; get them from",
    "> https://github.com/SandroDuarsa/lawful-ui/tree/main/skills/lawful-ui/scripts or measure by hand.",
    "",
    "# Part 1: The laws and the two modes",
    "",
    demote(body),
]
for rel, part in PARTS:
    chunks += ["", "---", "", f"# {part}: `{rel}`", "", demote((SKILL / rel).read_text().strip())]

(ROOT / "lawful-ui.md").write_text("\n".join(chunks) + "\n")
print("wrote lawful-ui.md,", len((ROOT / "lawful-ui.md").read_text()) // 1024, "KB")
